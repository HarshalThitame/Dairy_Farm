const AHILYANAGAR_DISTRICT_ALIASES = new Set([
  "अहिल्यानगर",
  "अहमदनगर",
  "ahilyanagar",
  "ahmednagar",
  "ahmadnagar"
]);

export function isAhilyanagarDistrict(value = "") {
  const normalized = String(value).trim().toLowerCase();
  return AHILYANAGAR_DISTRICT_ALIASES.has(normalized);
}

export function getAhilyanagarTalukas() {
  return AHILYANAGAR_TALUKA_VILLAGES.map((item) => item.taluka);
}

export function getAhilyanagarVillages(talukaName = "") {
  const normalized = String(talukaName).trim();
  const match = AHILYANAGAR_TALUKA_VILLAGES.find((item) => item.taluka === normalized);
  return match?.villages || [];
}

export function getAhilyanagarVillageCount() {
  return AHILYANAGAR_TALUKA_VILLAGES.reduce((count, item) => count + item.villages.length, 0);
}
